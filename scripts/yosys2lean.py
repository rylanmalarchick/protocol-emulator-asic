#!/usr/bin/env python3
"""Convert a flat yosys gate netlist (write_json after techmap) into a Lean model.

The Lean model is a structure of named Bool state bits (one per flip-flop), a
structure of Bool input bits, a `step` function for one rising clock edge, and
an `init` state from the `init` attributes.

Supported cells: $_NOT_ $_AND_ $_OR_ $_XOR_ $_MUX_ $_DFF_P_ $_DFFE_PP_ $_DFFE_PN_.
Any other cell type stops the conversion. One clock only.

Usage:
    yosys2lean.py net.json <module> <Lean namespace> > Model.lean
"""

import json
import re
import sys

COMB = {"$_NOT_", "$_AND_", "$_OR_", "$_XOR_", "$_MUX_"}
FLOPS = {"$_DFF_P_", "$_DFFE_PP_", "$_DFFE_PN_"}


def lean_name(name, index, width):
    base = re.sub(r"[^A-Za-z0-9_]", "_", name.lstrip("\\$"))
    return f"{base}_{index}" if width > 1 else base


def main(path, module, namespace):
    mod = json.load(open(path))["modules"][module]
    cells = mod["cells"]

    unknown = sorted({c["type"] for c in cells.values()} - COMB - FLOPS)
    if unknown:
        sys.exit(f"yosys2lean: unsupported cells: {unknown}")

    # Readable names for nets that a named wire carries.
    net_names = {}
    for name, net in mod["netnames"].items():
        if net.get("hide_name"):
            continue
        for i, bit in enumerate(net["bits"]):
            if isinstance(bit, int):
                net_names.setdefault(bit, lean_name(name, i, len(net["bits"])))

    inputs, outputs = [], []
    input_bits = {}
    for name, port in mod["ports"].items():
        for i, bit in enumerate(port["bits"]):
            field = lean_name(name, i, len(port["bits"]))
            if port["direction"] == "input":
                if name == "clk":
                    continue
                inputs.append(field)
                input_bits[bit] = f"i.{field}"
            else:
                outputs.append((field, bit))

    flops = [c for c in cells.values() if c["type"] in FLOPS]
    clocks = {c["connections"]["C"][0] for c in flops}
    if len(clocks) != 1:
        sys.exit(f"yosys2lean: expected one clock, found {len(clocks)}")

    state_bits = {}
    state_fields = []
    for c in sorted(flops, key=lambda c: net_names.get(c["connections"]["Q"][0], "")):
        q = c["connections"]["Q"][0]
        field = net_names.get(q, f"q{q}")
        state_fields.append(field)
        state_bits[q] = f"s.{field}"

    def ref(bit):
        if bit == "0":
            return "false"
        if bit == "1":
            return "true"
        if isinstance(bit, str):
            sys.exit(f"yosys2lean: undriven or x bit {bit!r}")
        if bit in input_bits:
            return input_bits[bit]
        if bit in state_bits:
            return state_bits[bit]
        return f"n{bit}"

    # Topological order of the combinational cells.
    driver = {}
    for cname, c in cells.items():
        if c["type"] in COMB:
            driver[c["connections"]["Y"][0]] = cname
    order, done, visiting = [], set(), set()

    def visit(cname):
        if cname in done:
            return
        if cname in visiting:
            sys.exit(f"yosys2lean: combinational loop at {cname}")
        visiting.add(cname)
        c = cells[cname]
        for port, bits in c["connections"].items():
            if port != "Y" and isinstance(bits[0], int) and bits[0] in driver:
                visit(driver[bits[0]])
        visiting.discard(cname)
        done.add(cname)
        order.append(cname)

    for cname in sorted(driver.values()):
        visit(cname)

    def expr(c):
        k = c["connections"]
        a = ref(k["A"][0])
        if c["type"] == "$_NOT_":
            return f"!{a}"
        b = ref(k["B"][0])
        if c["type"] == "$_AND_":
            return f"{a} && {b}"
        if c["type"] == "$_OR_":
            return f"{a} || {b}"
        if c["type"] == "$_XOR_":
            return f"xor {a} {b}"
        # $_MUX_: Y = S ? B : A
        return f"if {ref(k['S'][0])} then {b} else {a}"

    def next_state(c):
        k = c["connections"]
        d, q = ref(k["D"][0]), ref(k["Q"][0])
        if c["type"] == "$_DFF_P_":
            return d
        e = ref(k["E"][0])
        if c["type"] == "$_DFFE_PP_":
            return f"if {e} then {d} else {q}"
        return f"if {e} then {q} else {d}"

    init = {}
    for name, net in mod["netnames"].items():
        value = net.get("attributes", {}).get("init")
        if value is None:
            continue
        # init strings are MSB first; bits are LSB first.
        for i, bit in enumerate(net["bits"]):
            if bit in state_bits:
                init[bit] = value[::-1][i] == "1"

    out = []
    out.append(f"/-! Generated by scripts/yosys2lean.py from module `{module}`. Do not edit. -/")
    out.append("")
    out.append(f"namespace {namespace}")
    out.append("")
    out.append("structure St where")
    for f in state_fields:
        out.append(f"  {f} : Bool")
    out.append("  deriving DecidableEq, Repr")
    out.append("")
    out.append("structure In where")
    for f in inputs:
        out.append(f"  {f} : Bool")
    out.append("  deriving DecidableEq, Repr")
    out.append("")
    out.append("/-- One rising edge of the clock. -/")
    out.append("def step (s : St) (i : In) : St :=")
    for cname in order:
        c = cells[cname]
        out.append(f"  let n{c['connections']['Y'][0]} := {expr(c)}")
    out.append("  {")
    fields = []
    for c in sorted(flops, key=lambda c: net_names.get(c["connections"]["Q"][0], "")):
        q = c["connections"]["Q"][0]
        fields.append(f"    {net_names.get(q, f'q{q}')} := {next_state(c)}")
    out.append(",\n".join(fields))
    out.append("  }")
    out.append("")
    out.append("/-- Power-on state from the `init` attributes. -/")
    out.append("def init : St :=")
    out.append("  {")
    out.append(",\n".join(
        f"    {state_bits[q][2:]} := {'true' if init.get(q, False) else 'false'}"
        for c in sorted(flops, key=lambda c: net_names.get(c["connections"]["Q"][0], ""))
        for q in [c["connections"]["Q"][0]]))
    out.append("  }")
    out.append("")
    for field, bit in outputs:
        if bit not in state_bits:
            sys.exit(f"yosys2lean: output {field} is not a flip-flop output")
        out.append(f"def St.out_{field} (s : St) : Bool := {state_bits[bit]}")
    out.append("")
    out.append(f"end {namespace}")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
